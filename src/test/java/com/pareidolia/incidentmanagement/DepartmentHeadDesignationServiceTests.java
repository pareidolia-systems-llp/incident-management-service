package com.pareidolia.incidentmanagement;

import com.pareidolia.incidentmanagement.entity.AppUser;
import com.pareidolia.incidentmanagement.repository.AppUserRepository;
import com.pareidolia.incidentmanagement.security.EmployeeManagementAccess;
import com.pareidolia.incidentmanagement.service.AppUserService;
import com.pareidolia.incidentmanagement.service.DepartmentHeadDesignationService;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.server.ResponseStatusException;
import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;

@DataJpaTest(properties={"spring.jpa.hibernate.ddl-auto=create-drop","app.department-head-designations.enabled=true"})
@Import(DepartmentHeadDesignationService.class)
@Transactional(propagation=Propagation.NOT_SUPPORTED)
class DepartmentHeadDesignationServiceTests {
    @Autowired JdbcTemplate db;
    @Autowired AppUserRepository repository;
    @Autowired DepartmentHeadDesignationService service;
    @MockitoBean AppUserService users;
    @MockitoBean EmployeeManagementAccess access;
    AppUser actor, employee;
    @BeforeEach void setup() {
        db.execute("create table if not exists employee_departments (id bigint primary key,display_name varchar(150),active tinyint not null)");
        db.execute("create table if not exists employee_mapping_admins (user_id bigint primary key,active tinyint)");
        db.execute("create table if not exists department_head_designations (department_id bigint,user_id bigint,active tinyint not null,version bigint not null,primary key(department_id,user_id))");
        db.execute("create table if not exists department_head_designation_audit (id bigint generated by default as identity primary key,department_id bigint,user_id bigint,actor_user_id bigint,old_active tinyint,new_active tinyint,designation_version bigint,reason varchar(500) check (reason <> 'audit failure'),changed_at timestamp default current_timestamp)");
        db.update("delete from department_head_designation_audit");db.update("delete from department_head_designations");db.update("delete from employee_mapping_admins");db.update("delete from employee_departments");
        actor=account("manager@example.test");employee=account("person@example.test");
        db.update("insert into employee_departments(id,display_name,active) values (1,'Synthetic IT',1),(2,'Synthetic Ops',1)");
        db.update("insert into employee_mapping_admins(user_id,active) values (?,1)",actor.getId());
        when(users.getAuthenticatedUser()).thenReturn(actor);when(access.canManage(actor)).thenReturn(true);
    }
    private AppUser account(String email) {
        var a=repository.findByEmail(email).orElseGet(AppUser::new); a.setEmail(email); a.setDisplayName("Synthetic"); a.setActive(true); return repository.saveAndFlush(a);
    }
    @Test void addMultipleDepartmentsRemoveAndAuditWithoutGrantingMembership() {
        assertThat(service.set(1L,employee.getId(),true,null,"Approved designation")).isZero();
        assertThat(service.set(2L,employee.getId(),true,null,"Second department")).isZero();
        assertThat(service.list()).hasSize(2);assertThat(service.departments()).hasSize(2);
        assertThat(service.history(1L,employee.getId())).singleElement().satisfies(event -> {
            assertThat(event.actorUserId()).isEqualTo(actor.getId());assertThat(event.reason()).isEqualTo("Approved designation");
        });
        assertThat(service.set(1L,employee.getId(),false,0L,"Change of duty")).isEqualTo(1L);
        assertThat(db.queryForObject("select count(*) from department_head_designation_audit",Long.class)).isEqualTo(3);
        assertThat(db.queryForObject("select count(*) from information_schema.tables where table_name = 'DEPARTMENT_MEMBERSHIPS'",Long.class)).isZero();
        assertThat(db.queryForObject("select active from department_head_designations where department_id=1",Integer.class)).isZero();
    }
    @Test void deniedAndStaleChangesDoNotWrite() {
        when(access.canManage(actor)).thenReturn(false);
        assertThatThrownBy(() -> service.set(1L,employee.getId(),true,null,"Reason")).isInstanceOf(AccessDeniedException.class);
        when(access.canManage(actor)).thenReturn(true);
        db.update("update employee_mapping_admins set active=0 where user_id=?",actor.getId());
        assertThatThrownBy(() -> service.set(1L,employee.getId(),true,null,"Reason")).isInstanceOf(AccessDeniedException.class);
        db.update("update employee_mapping_admins set active=1 where user_id=?",actor.getId());
        service.set(1L,employee.getId(),true,null,"Reason");
        assertThatThrownBy(() -> service.set(1L,employee.getId(),false,9L,"Reason")).isInstanceOf(ResponseStatusException.class);
        assertThat(db.queryForObject("select active from department_head_designations where department_id=1",Integer.class)).isEqualTo(1);
        assertThat(db.queryForObject("select count(*) from department_head_designation_audit",Long.class)).isEqualTo(1);
    }
    @Test void auditFailureRollsBackDesignation() {
        assertThatThrownBy(() -> service.set(1L,employee.getId(),true,null,"audit failure")).isInstanceOf(RuntimeException.class);
        assertThat(db.queryForObject("select count(*) from department_head_designations",Long.class)).isZero();
        assertThat(db.queryForObject("select count(*) from department_head_designation_audit",Long.class)).isZero();
    }
    @Test void inactiveEmployeeDesignationCanBeRemovedButNotAdded() {
        service.set(1L,employee.getId(),true,null,"Reason");
        db.update("update app_users set active=false where id=?",employee.getId());
        assertThat(service.set(1L,employee.getId(),false,0L,"Removal after deactivation")).isEqualTo(1L);
        assertThatThrownBy(() -> service.set(1L,employee.getId(),true,1L,"Reason")).isInstanceOf(AccessDeniedException.class);
        assertThat(db.queryForObject("select count(*) from department_head_designation_audit",Long.class)).isEqualTo(2);
    }
    @Test void changedAuthenticatedAccountEmailDeniesEvenWhenOldPrincipalIsStillInMemory() {
        db.update("update app_users set email='replacement@example.test' where id=?",actor.getId());
        assertThatThrownBy(() -> service.set(1L,employee.getId(),true,null,"Reason")).isInstanceOf(AccessDeniedException.class);
        assertThat(db.queryForObject("select count(*) from department_head_designations",Long.class)).isZero();
        assertThat(db.queryForObject("select count(*) from department_head_designation_audit",Long.class)).isZero();
        db.update("update app_users set email='manager@example.test' where id=?",actor.getId());
    }
    @Test void capabilityRevocationCommittedBeforeLocksCannotAuthorizeMutation() throws Exception {
        var started=new java.util.concurrent.CountDownLatch(1);var release=new java.util.concurrent.CountDownLatch(1);
        when(access.canManage(actor)).thenAnswer(inv -> {
            db.queryForObject("select active from employee_mapping_admins where user_id=?",Integer.class,actor.getId());
            started.countDown();if(!release.await(10,java.util.concurrent.TimeUnit.SECONDS))throw new IllegalStateException("Timed out");return true;
        });
        var executor=java.util.concurrent.Executors.newSingleThreadExecutor();
        try {
            var attempt=executor.submit(() -> service.set(1L,employee.getId(),true,null,"Reason"));
            assertThat(started.await(10,java.util.concurrent.TimeUnit.SECONDS)).isTrue();
            db.update("update employee_mapping_admins set active=0 where user_id=?",actor.getId());release.countDown();
            assertThatThrownBy(() -> attempt.get(15,java.util.concurrent.TimeUnit.SECONDS))
                .isInstanceOf(java.util.concurrent.ExecutionException.class);
            assertThat(db.queryForObject("select count(*) from department_head_designations",Long.class)).isZero();
            assertThat(db.queryForObject("select count(*) from department_head_designation_audit",Long.class)).isZero();
        } finally {release.countDown();executor.shutdownNow();assertThat(executor.awaitTermination(10,java.util.concurrent.TimeUnit.SECONDS)).isTrue();}
    }
    @Test void inactiveEmployeeOrDepartmentIsDenied() {
        db.update("update app_users set active=false where id=?",employee.getId());
        assertThatThrownBy(() -> service.set(1L,employee.getId(),true,null,"Reason")).isInstanceOf(AccessDeniedException.class);
        db.update("update app_users set active=true where id=?",employee.getId());db.update("update employee_departments set active=0 where id=1");
        assertThatThrownBy(() -> service.set(1L,employee.getId(),true,null,"Reason")).isInstanceOf(AccessDeniedException.class);
        assertThat(db.queryForObject("select count(*) from department_head_designations",Long.class)).isZero();
    }
    @Test void concurrentDuplicateCreationCommitsOnlyOneDesignationAndAudit() throws Exception {
        var start = new java.util.concurrent.CountDownLatch(1);
        var pool = java.util.concurrent.Executors.newFixedThreadPool(2);
        try {
            java.util.concurrent.Callable<Boolean> attempt = () -> {
                if (!start.await(10,java.util.concurrent.TimeUnit.SECONDS)) throw new IllegalStateException("Timed out");
                try { service.set(1L,employee.getId(),true,null,"Concurrent designation"); return true; }
                catch (org.springframework.web.server.ResponseStatusException conflict) { if (conflict.getStatusCode().value()!=409) throw conflict; return false; }
            };
            var one=pool.submit(attempt); var two=pool.submit(attempt); start.countDown();
            assertThat(java.util.List.of(one.get(15,java.util.concurrent.TimeUnit.SECONDS),two.get(15,java.util.concurrent.TimeUnit.SECONDS)))
                .containsExactlyInAnyOrder(true,false);
            assertThat(db.queryForObject("select count(*) from department_head_designations",Long.class)).isEqualTo(1);
            assertThat(db.queryForObject("select count(*) from department_head_designation_audit",Long.class)).isEqualTo(1);
        } finally { start.countDown();pool.shutdownNow();assertThat(pool.awaitTermination(10,java.util.concurrent.TimeUnit.SECONDS)).isTrue(); }
    }
}
