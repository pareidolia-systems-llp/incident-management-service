package com.pareidolia.incidentmanagement;

import com.pareidolia.incidentmanagement.dto.*;
import com.pareidolia.incidentmanagement.entity.AppUser;
import com.pareidolia.incidentmanagement.repository.AppUserRepository;
import com.pareidolia.incidentmanagement.security.EmployeeManagementAccess;
import com.pareidolia.incidentmanagement.service.*;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.web.server.ResponseStatusException;
import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;

@DataJpaTest(properties={"app.employee-management.enabled=true","app.auth.allowed-domain=example.test"})
@Import(EmployeeDirectoryService.class)
@Transactional(propagation=Propagation.NOT_SUPPORTED)
class EmployeeDirectoryServiceTests {
    @Autowired JdbcTemplate db; @Autowired AppUserRepository repo; @Autowired EmployeeDirectoryService service;
    @MockitoBean AppUserService users; @MockitoBean EmployeeManagementAccess access;
    AppUser actor;
    @BeforeEach void setup(){
        db.execute("alter table app_users add column if not exists employee_id varchar(64) unique");
        db.execute("alter table app_users add column if not exists account_version bigint not null default 0");
        db.execute("create table if not exists employee_management_audit(id bigint generated by default as identity primary key,actor_id bigint,target_id bigint,action varchar(20),old_employee_id varchar(64),new_employee_id varchar(64),old_name varchar(255),new_name varchar(255),old_active tinyint,new_active tinyint,version bigint,reason varchar(500) check(reason <> 'audit failure'),changed_at timestamp default current_timestamp)");
        db.update("delete from employee_management_audit");db.update("delete from app_users where email <> 'manager@example.test'");
        actor=repo.findByEmail("manager@example.test").orElseGet(AppUser::new);actor.setEmail("manager@example.test");actor.setDisplayName("Manager");actor.setActive(true);actor=repo.saveAndFlush(actor);
        when(users.getAuthenticatedUser()).thenReturn(actor);when(access.canManage(actor)).thenReturn(true);
    }
    @Test void createSearchUpdateAndDeactivateAreAuditedAndVersioned(){
        var created=service.create(new CreateEmployeeRequest("E-100","Synthetic Person","Person@example.test"));
        assertThat(created.officialEmail()).isEqualTo("person@example.test");assertThat(created.version()).isZero();
        assertThat(service.list("person@",0,20).content()).hasSize(1);
        var updated=service.update(created.id(),new UpdateEmployeeRequest("E-101","Updated Person","Correction",0L));
        assertThat(updated.version()).isEqualTo(1);assertThat(updated.employeeId()).isEqualTo("E-101");
        assertThatThrownBy(() -> service.status(created.id(),false,0L,"Left")).isInstanceOf(ResponseStatusException.class);
        assertThat(service.status(created.id(),false,1L,"Left").active()).isFalse();
        assertThat(db.queryForObject("select count(*) from employee_management_audit",Long.class)).isEqualTo(3); assertThat(service.history(created.id())).hasSize(3);
    }
    @Test void preservesExactEmployeeIdsAndRequiresAnEditReason() {
        var created = service.create(new CreateEmployeeRequest(" 000Ab_ ", "Synthetic Person", "exact@example.test"));
        assertThat(created.employeeId()).isEqualTo(" 000Ab_ ");
        assertThat(repo.findById(created.id()).orElseThrow().getRole())
                .isEqualTo(com.pareidolia.incidentmanagement.enums.AppUserRole.REPORTER);
        assertThat(service.list("_", 0, 20).content()).extracting(EmployeeResponse::id)
                .containsExactly(created.id());
        assertThatThrownBy(() -> service.update(created.id(),
                new UpdateEmployeeRequest(" 000Cd ", "Synthetic Person", " ", 0L)))
                .isInstanceOf(ResponseStatusException.class);
        var updated = service.update(created.id(),
                new UpdateEmployeeRequest(" 000Cd ", "Synthetic Person", "HR correction", 0L));
        assertThat(updated.employeeId()).isEqualTo(" 000Cd ");
        assertThat(service.history(created.id()).get(0).oldEmployeeId()).isEqualTo(" 000Ab_ ");
        assertThat(service.status(created.id(), false, 1L, "Leave").active()).isFalse();
        assertThat(service.status(created.id(), true, 2L, "Returned").active()).isTrue();
    }

    @Test void auditFailureRollsBackEmployeeUpdate(){
        var created=service.create(new CreateEmployeeRequest("E-200","Person","person@example.test"));
        assertThatThrownBy(() -> service.update(created.id(),new UpdateEmployeeRequest("E-201","Person Two","audit failure",0L))).isInstanceOf(RuntimeException.class);
        assertThat(service.view(created.id()).employeeId()).isEqualTo("E-200");
    }
    @Test void duplicateEmployeeIdAndEmailAreRejected() {
        service.create(new CreateEmployeeRequest("E-400","First","first@example.test"));
        assertThatThrownBy(() -> service.create(new CreateEmployeeRequest("E-400","Second","second@example.test"))).isInstanceOf(ResponseStatusException.class);
        assertThatThrownBy(() -> service.create(new CreateEmployeeRequest("E-401","First Again","first@example.test"))).isInstanceOf(ResponseStatusException.class);
        assertThat(service.list("first@example.test",0,20).content()).hasSize(1);
    }
    @Test void nonCompanyEmailIsRejected(){assertThatThrownBy(() -> service.create(new CreateEmployeeRequest("E-300","Other","person@outside.test"))).isInstanceOf(ResponseStatusException.class);}
    @Test void unauthorizedAccessIsDenied(){when(access.canManage(actor)).thenReturn(false);assertThatThrownBy(() -> service.list("",0,20)).isInstanceOf(AccessDeniedException.class);}
}
