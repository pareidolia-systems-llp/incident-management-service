package com.pareidolia.incidentmanagement;

import com.pareidolia.incidentmanagement.entity.AppUser;
import com.pareidolia.incidentmanagement.repository.AppUserRepository;
import com.pareidolia.incidentmanagement.security.EmployeeManagementAccess;
import com.pareidolia.incidentmanagement.service.AppUserService;
import com.pareidolia.incidentmanagement.service.EmployeeMappingCapabilityService;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;
import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;

@DataJpaTest(properties={"spring.jpa.hibernate.ddl-auto=create-drop","app.employee-capability-management.enabled=true","app.department-head-designations.enabled=true"})
@Import({EmployeeMappingCapabilityService.class, com.pareidolia.incidentmanagement.service.DepartmentHeadDesignationService.class})
@Transactional(propagation=Propagation.NOT_SUPPORTED)
class EmployeeMappingCapabilityServiceTests {
    @Autowired JdbcTemplate db;
    @Autowired AppUserRepository repo;
    @Autowired EmployeeMappingCapabilityService service;
    @Autowired com.pareidolia.incidentmanagement.service.DepartmentHeadDesignationService designations;
    @Autowired org.springframework.transaction.PlatformTransactionManager transactions;
    @MockitoBean AppUserService users;
    @MockitoBean EmployeeManagementAccess access;
    AppUser actor,target;
    @BeforeEach void setup() {
        db.execute("create table if not exists employee_departments(id bigint primary key,display_name varchar(150),active tinyint not null)");
        db.execute("create table if not exists department_head_designations(department_id bigint,user_id bigint,active tinyint,version bigint,primary key(department_id,user_id))");
        db.execute("create table if not exists department_head_designation_audit(id bigint generated by default as identity primary key,department_id bigint,user_id bigint,actor_user_id bigint,old_active tinyint,new_active tinyint,designation_version bigint,reason varchar(500),changed_at timestamp default current_timestamp)");
        db.execute("create table if not exists employee_mapping_admins(user_id bigint primary key,active tinyint not null)");
        db.execute("create table if not exists employee_capability_administrators(user_id bigint primary key,active tinyint not null)");
        db.execute("create table if not exists employee_mapping_admin_audit(id bigint generated by default as identity primary key,actor_user_id bigint,target_user_id bigint,old_active tinyint,new_active tinyint,reason varchar(500) check(reason <> 'audit failure'),changed_at timestamp default current_timestamp)");
        db.update("delete from department_head_designation_audit"); db.update("delete from department_head_designations"); db.update("delete from employee_departments");
        db.update("delete from employee_mapping_admin_audit"); db.update("delete from employee_mapping_admins"); db.update("delete from employee_capability_administrators");
        actor=account("cap-admin@example.test"); target=account("mapping-target@example.test");
        db.update("insert into employee_capability_administrators values (?,1)",actor.getId());
        when(users.getAuthenticatedUser()).thenReturn(actor); when(access.canManage(actor)).thenReturn(true);
    }
    AppUser account(String email) { var a=repo.findByEmail(email).orElseGet(AppUser::new);a.setEmail(email);a.setDisplayName("Synthetic");a.setActive(true);return repo.saveAndFlush(a); }
    @Test void grantRevokeAndIdempotencyAreAudited() {
        assertThat(service.setMappingAdmin(target.getId(),true,"Approved")).isTrue();
        assertThat(service.setMappingAdmin(target.getId(),true,"No change")).isFalse();
        assertThat(service.setMappingAdmin(target.getId(),false,"Revoked")).isTrue();
        assertThat(db.queryForObject("select count(*) from employee_mapping_admin_audit",Long.class)).isEqualTo(2);
        assertThat(db.queryForList("select old_active,new_active from employee_mapping_admin_audit order by id")).hasSize(2);
        assertThat(db.queryForObject("select active from employee_mapping_admins where user_id=?",Integer.class,target.getId())).isZero();
    }
    @Test void deniesSelfGrantUnapprovedInactiveAndUnverifiedActor() {
        assertThatThrownBy(() -> service.setMappingAdmin(actor.getId(),true,"Reason")).isInstanceOf(AccessDeniedException.class);
        db.update("update employee_capability_administrators set active=0 where user_id=?",actor.getId());
        assertThatThrownBy(() -> service.setMappingAdmin(target.getId(),true,"Reason")).isInstanceOf(AccessDeniedException.class);
        db.update("update employee_capability_administrators set active=1 where user_id=?",actor.getId());
        when(access.canManage(actor)).thenReturn(false);
        assertThatThrownBy(() -> service.setMappingAdmin(target.getId(),true,"Reason")).isInstanceOf(AccessDeniedException.class);
        assertThat(db.queryForObject("select count(*) from employee_mapping_admin_audit",Long.class)).isZero();
    }
    @Test void auditFailureRollsBackGrant() {
        assertThatThrownBy(() -> service.setMappingAdmin(target.getId(),true,"audit failure")).isInstanceOf(RuntimeException.class);
        assertThat(db.queryForObject("select count(*) from employee_mapping_admins",Long.class)).isZero();
        assertThat(db.queryForObject("select count(*) from employee_mapping_admin_audit",Long.class)).isZero();
    }
    @Test void concurrentGrantsProduceOneChangeAndOneAudit() throws Exception {
        var start=new java.util.concurrent.CountDownLatch(1); var pool=java.util.concurrent.Executors.newFixedThreadPool(2);
        try {
            java.util.concurrent.Callable<Boolean> task=() -> { if(!start.await(10,java.util.concurrent.TimeUnit.SECONDS))throw new IllegalStateException(); return service.setMappingAdmin(target.getId(),true,"Concurrent"); };
            var a=pool.submit(task);var b=pool.submit(task);start.countDown();
            assertThat(java.util.List.of(a.get(15,java.util.concurrent.TimeUnit.SECONDS),b.get(15,java.util.concurrent.TimeUnit.SECONDS))).containsExactlyInAnyOrder(true,false);
            assertThat(db.queryForObject("select count(*) from employee_mapping_admin_audit",Long.class)).isEqualTo(1);
        } finally {start.countDown();pool.shutdownNow();assertThat(pool.awaitTermination(10,java.util.concurrent.TimeUnit.SECONDS)).isTrue();}
    }
    @Test void committedRevocationPreventsConcurrentDesignation() throws Exception {
        var employee=account("designation-person@example.test");
        db.update("insert into employee_departments values (1,'Synthetic',1)");
        db.update("insert into employee_mapping_admins values (?,1)",target.getId());
        when(access.canManage(target)).thenReturn(true);
        when(users.getAuthenticatedUser()).thenAnswer(inv -> Thread.currentThread().getName().startsWith("designation-") ? target : actor);
        var changed=new java.util.concurrent.CountDownLatch(1); var commit=new java.util.concurrent.CountDownLatch(1);
        var starting=new java.util.concurrent.CountDownLatch(1);
        var pool=java.util.concurrent.Executors.newSingleThreadExecutor();
        var worker=java.util.concurrent.Executors.newSingleThreadExecutor(r -> new Thread(r,"designation-worker"));
        try {
            var revoke=pool.submit(() -> {
                var tx=new org.springframework.transaction.support.TransactionTemplate(transactions);
                tx.setIsolationLevel(org.springframework.transaction.TransactionDefinition.ISOLATION_REPEATABLE_READ);
                return tx.execute(status -> { service.setMappingAdmin(target.getId(),false,"Revoke"); changed.countDown();
                    try { if(!commit.await(10,java.util.concurrent.TimeUnit.SECONDS)) throw new IllegalStateException("Timed out"); }
                    catch(InterruptedException e){Thread.currentThread().interrupt();throw new IllegalStateException(e);} return true; });
            });
            assertThat(changed.await(10,java.util.concurrent.TimeUnit.SECONDS)).isTrue();
            var attempt=worker.submit(() -> {starting.countDown(); return designations.set(1L,employee.getId(),true,null,"Denied");});
            assertThat(starting.await(10,java.util.concurrent.TimeUnit.SECONDS)).isTrue(); commit.countDown();
            assertThat(revoke.get(15,java.util.concurrent.TimeUnit.SECONDS)).isTrue();
            assertThatThrownBy(() -> attempt.get(15,java.util.concurrent.TimeUnit.SECONDS)).isInstanceOf(java.util.concurrent.ExecutionException.class).hasCauseInstanceOf(AccessDeniedException.class);
            assertThat(db.queryForObject("select count(*) from department_head_designations",Long.class)).isZero();
            assertThat(db.queryForObject("select count(*) from department_head_designation_audit",Long.class)).isZero();
            assertThat(db.queryForObject("select count(*) from employee_mapping_admin_audit",Long.class)).isEqualTo(1);
        } finally {commit.countDown(); pool.shutdownNow();worker.shutdownNow();assertThat(pool.awaitTermination(10,java.util.concurrent.TimeUnit.SECONDS)).isTrue();assertThat(worker.awaitTermination(10,java.util.concurrent.TimeUnit.SECONDS)).isTrue();}
    }
}
