package com.pareidolia.incidentmanagement;

import com.pareidolia.incidentmanagement.entity.AppUser;
import com.pareidolia.incidentmanagement.repository.AppUserRepository;
import com.pareidolia.incidentmanagement.security.EmployeeManagementAccess;
import com.pareidolia.incidentmanagement.service.AppUserService;
import com.pareidolia.incidentmanagement.service.HandlerEligibilityAdminService;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.server.ResponseStatusException;
import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;

@DataJpaTest(properties={"app.handler-eligibility-admin.enabled=true","app.handler-eligibility-admin.allowed-emails=manager@example.test"})
@Import(HandlerEligibilityAdminService.class)
@Transactional(propagation=Propagation.NOT_SUPPORTED)
class HandlerEligibilityAdminServiceTests {
    @Autowired JdbcTemplate db; @Autowired AppUserRepository repo; @Autowired HandlerEligibilityAdminService service;
    @MockitoBean AppUserService users; @MockitoBean EmployeeManagementAccess access;
    AppUser actor,target;
    @BeforeEach void setup() {
        db.execute("create table if not exists handler_eligibility_grants(user_id bigint primary key,active tinyint not null,version bigint not null)");
        db.execute("create table if not exists handler_eligibility_audit(id bigint generated by default as identity primary key,actor_user_id bigint,target_user_id bigint,old_active tinyint,new_active tinyint,grant_version bigint,reason varchar(500) check(reason <> 'audit failure'),changed_at timestamp default current_timestamp)");
        db.update("delete from handler_eligibility_audit"); db.update("delete from handler_eligibility_grants");
        actor=account("manager@example.test"); target=account("handler@example.test");
        when(users.getAuthenticatedUser()).thenReturn(actor); when(access.canManage(actor)).thenReturn(true);
    }
    AppUser account(String email) {var u=repo.findByEmail(email).orElseGet(AppUser::new);u.setEmail(email);u.setDisplayName("Synthetic");u.setActive(true);return repo.saveAndFlush(u);}
    @Test void grantRevokeAndHistoryAreVersioned() {
        assertThat(service.change(target.getId(),true,null,"Approved")).isZero();
        assertThat(service.list()).singleElement().satisfies(g -> assertThat(g.userId()).isEqualTo(target.getId()));
        assertThatThrownBy(() -> service.change(target.getId(),false,9L,"reason")).isInstanceOf(ResponseStatusException.class);
        assertThat(service.change(target.getId(),false,0L,"Change")).isEqualTo(1);
        assertThat(service.history(target.getId())).hasSize(2);
    }
    @Test void deniesSelfAndUnauthorizedAndInactiveGrants() {
        assertThatThrownBy(() -> service.change(actor.getId(),true,null,"Reason")).isInstanceOf(AccessDeniedException.class);
        when(access.canManage(actor)).thenReturn(false);
        assertThatThrownBy(() -> service.change(target.getId(),true,null,"Reason")).isInstanceOf(AccessDeniedException.class);
        when(access.canManage(actor)).thenReturn(true);
        db.update("update app_users set active=false where id=?",target.getId());
        assertThatThrownBy(() -> service.change(target.getId(),true,null,"Reason")).isInstanceOf(AccessDeniedException.class);
        assertThat(db.queryForObject("select count(*) from handler_eligibility_grants",Long.class)).isZero();
    }
    @Test void auditFailureRollsBackGrant() {
        assertThatThrownBy(() -> service.change(target.getId(),true,null,"audit failure")).isInstanceOf(RuntimeException.class);
        assertThat(db.queryForObject("select count(*) from handler_eligibility_grants",Long.class)).isZero();
    }
}
