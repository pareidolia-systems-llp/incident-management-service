package com.pareidolia.incidentmanagement;

import com.pareidolia.incidentmanagement.entity.AppUser;
import com.pareidolia.incidentmanagement.repository.AppUserRepository;
import com.pareidolia.incidentmanagement.service.*;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.security.oauth2.core.oidc.user.OidcUser;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.server.ResponseStatusException;
import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;

@DataJpaTest(properties={"app.incident-security-admin.enabled=true","app.incident-access.enabled=true","app.incident-capability-admin.allowed-emails=bootstrap@example.test"})
@Import({IncidentCapabilityAdministrationService.class,com.pareidolia.incidentmanagement.security.IncidentSecurityGate.class,com.pareidolia.incidentmanagement.security.IncidentReadSnapshot.class})
@Transactional(propagation=Propagation.NOT_SUPPORTED)
class IncidentCapabilityAdministrationServiceTests {
    @Autowired JdbcTemplate db;@Autowired AppUserRepository repository;@Autowired IncidentCapabilityAdministrationService service;@MockitoBean AppUserService authenticated;
    AppUser actor,target;
    @BeforeEach void setup(){
        db.execute("create table if not exists incident_security_lock(id bigint primary key)");
        if(db.queryForObject("select count(*) from incident_security_lock",Long.class)==0)db.update("insert into incident_security_lock values(1)");
        db.execute("create table if not exists assignment_admin_capabilities(user_id bigint,capability varchar(40),active tinyint,version bigint,primary key(user_id,capability))");
        db.execute("create table if not exists assignment_admin_capability_audit(id bigint generated by default as identity primary key,actor_user_id bigint,target_user_id bigint,capability varchar(40),old_active tinyint,new_active tinyint,version bigint,reason varchar(500) check(reason <> 'audit failure'),changed_at timestamp default current_timestamp)");
        db.update("delete from assignment_admin_capability_audit");db.update("delete from assignment_admin_capabilities");actor=account("bootstrap@example.test");target=account("target@example.test");
        when(authenticated.getAuthenticatedUser()).thenReturn(actor);var oidc=mock(OidcUser.class);when(oidc.getEmail()).thenReturn(actor.getEmail());when(oidc.getEmailVerified()).thenReturn(true);
        SecurityContextHolder.getContext().setAuthentication(new UsernamePasswordAuthenticationToken(oidc,"",java.util.List.of()));
    }
    AppUser account(String email){var u=repository.findByEmail(email).orElseGet(AppUser::new);u.setEmail(email);u.setDisplayName("Synthetic");u.setActive(true);return repository.saveAndFlush(u);}
    @AfterEach void clear(){SecurityContextHolder.clearContext();}
    @Test void capabilitiesAreIndependentVersionedAndAudited(){
        assertThat(service.change(target.getId(),"INCIDENT_CLASSIFIER",true,0L,"Approved")).isEqualTo(1);
        assertThat(service.list()).singleElement().satisfies(c->assertThat(c.capability()).isEqualTo("INCIDENT_CLASSIFIER"));
        assertThatThrownBy(()->service.change(target.getId(),"INCIDENT_CLASSIFIER",false,0L,"Stale")).isInstanceOf(ResponseStatusException.class);
        assertThat(service.change(target.getId(),"INCIDENT_CLASSIFIER",false,1L,"Revoked")).isEqualTo(2);
        assertThat(service.history(target.getId(),"INCIDENT_CLASSIFIER")).hasSize(2);
        assertThatThrownBy(()->service.change(actor.getId(),"CASE_ACCESS_ADMIN",true,0L,"Self")).isInstanceOf(AccessDeniedException.class);
    }
    @Test void auditFailureRollsBackGrant(){
        assertThatThrownBy(()->service.change(target.getId(),"CASE_ACCESS_ADMIN",true,0L,"audit failure")).isInstanceOf(RuntimeException.class);
        assertThat(db.queryForObject("select count(*) from assignment_admin_capabilities",Long.class)).isZero();
    }
    @Test void unverifiedOrInactiveBootstrapCannotGrant(){
        var oidc=mock(OidcUser.class);when(oidc.getEmail()).thenReturn(actor.getEmail());when(oidc.getEmailVerified()).thenReturn(false);
        SecurityContextHolder.getContext().setAuthentication(new UsernamePasswordAuthenticationToken(oidc,"",java.util.List.of()));
        assertThatThrownBy(()->service.change(target.getId(),"CASE_ACCESS_ADMIN",true,0L,"Reason")).isInstanceOf(AccessDeniedException.class);
        when(oidc.getEmailVerified()).thenReturn(true);db.update("update app_users set active=false where id=?",actor.getId());
        assertThatThrownBy(()->service.change(target.getId(),"CASE_ACCESS_ADMIN",true,0L,"Reason")).isInstanceOf(AccessDeniedException.class);
    }
}
